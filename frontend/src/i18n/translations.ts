export const translations: Record<Language, Record<TranslationKey, string>> = { it, en }

export function translate(language: Language, key: TranslationKey, params?: TranslateParams): string {
  const template: string | undefined = translations[language][key] ?? translations.it[key]
  if (template === undefined) {
    if (import.meta.env?.DEV) console.warn(`[i18n] Missing translation: ${key}`)
    return `[missing: ${key}]`
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params && name in params ? String(params[name]) : match,
  )
}
