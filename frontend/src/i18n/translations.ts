export type Language = 'it' | 'en'
export const LANGUAGES: Language[] = ['it', 'en']
export const LANGUAGE_STORAGE_KEY = 'studyos.language'
export const LOCALES: Record<Language, string> = { it: 'it-IT', en: 'en-US' }

export function isLanguage(value: unknown): value is Language {
  return value === 'it' || value === 'en'
}

/** Stored choice wins; otherwise browser language; fallback Italian (source locale). */
export function resolveInitialLanguage(stored: string | null, browserLanguage?: string | null): Language {
  if (isLanguage(stored)) return stored
  if (browserLanguage?.toLowerCase().startsWith('en')) return 'en'
  return 'it'
}

